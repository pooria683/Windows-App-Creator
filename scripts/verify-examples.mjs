#!/usr/bin/env node
/**
 * Verify the committed examples match what the current templates + CLI
 * produce (guards against drift between templates and examples).
 *
 * Usage: node scripts/verify-examples.mjs
 * Exits non-zero on any mismatch, printing the differing files.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cli = path.join(repoRoot, 'packages/cli/dist/index.js');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'winforge-verify-'));

const cases = [
  {
    dir: 'examples/electron-hello',
    args: [
      'create',
      path.join(tmp, 'electron-hello'),
      '--template',
      'electron',
      '--ui',
      'react',
      '--pm',
      'npm',
      '--app-name',
      'Hello WinForge',
      '--package-id',
      'com.winforge.examples.hello',
      '--app-version',
      '0.1.0',
      '--author',
      'WinForge',
      '--description',
      'Example Electron app generated by WinForge.',
      '--non-interactive',
      '--no-install',
    ],
  },
  {
    dir: 'examples/tauri-hello',
    args: [
      'create',
      path.join(tmp, 'tauri-hello'),
      '--template',
      'tauri',
      '--ui',
      'react',
      '--pm',
      'npm',
      '--app-name',
      'Hello Tauri',
      '--package-id',
      'com.winforge.examples.taurihello',
      '--app-version',
      '0.1.0',
      '--author',
      'WinForge',
      '--description',
      'Example Tauri app generated by WinForge.',
      '--non-interactive',
      '--no-install',
    ],
  },
];

function walk(dir, base = dir, out = new Map()) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', 'dist', 'release', '.git', '.github'].includes(entry.name)) continue;
      walk(full, base, out);
    } else {
      out.set(path.relative(base, full), full);
    }
  }
  return out;
}

let failed = false;
for (const { dir, args } of cases) {
  execFileSync(process.execPath, [cli, ...args], { stdio: 'pipe' });
  const fresh = path.join(tmp, path.basename(dir));
  const a = walk(fresh);
  const b = walk(path.join(repoRoot, dir));

  const problems = [];
  for (const [rel, file] of a) {
    if (!b.has(rel)) problems.push(`missing in example: ${rel}`);
    else if (!fs.readFileSync(file).equals(fs.readFileSync(b.get(rel)))) {
      problems.push(`differs: ${rel}`);
    }
  }
  for (const rel of b.keys()) if (!a.has(rel)) problems.push(`extra in example: ${rel}`);

  if (problems.length) {
    failed = true;
    console.error(`\n✖ ${dir} is out of date:`);
    for (const p of problems) console.error(`   ${p}`);
  } else {
    console.log(`✔ ${dir} matches the templates (${a.size} files; .github/ checked by CI)`);
  }
}

fs.rmSync(tmp, { recursive: true, force: true });
if (failed) {
  console.error('\nRegenerate with: npm run create:example');
  process.exit(1);
}
